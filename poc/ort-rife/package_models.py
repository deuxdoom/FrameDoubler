"""Package FP32 RGB8 graphs with one shared weight file per RIFE model.

The four validated input graphs are generated by export_onnx.py and
convert_onnx_rgb8.py. No precision or spatial transformation is done here.
"""
import argparse
import hashlib
import json
from pathlib import Path

import onnx
from onnx.external_data_helper import set_external_data


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    for version in ("v4.25", "v4.26"):
        location = version + ".weights"
        # Rebuild deterministically. Both scales share byte-identical tensors.
        offsets = {}
        with (args.output / location).open("wb") as weights:
            for scale, suffix in (("1", "s1"), ("0.5", "s05")):
                model = onnx.load(args.input / f"{version}-s{scale}-rgb8.onnx")
                for tensor in model.graph.initializer:
                    raw = tensor.raw_data
                    if len(raw) < 1024:
                        continue
                    key = hashlib.sha256(raw).digest()
                    if key not in offsets:
                        offsets[key] = weights.tell()
                        weights.write(raw)
                    set_external_data(tensor, location, offset=offsets[key], length=len(raw))
                    tensor.ClearField("raw_data")
                onnx.save_model(model, args.output / f"{version}-{suffix}.onnx")
    for graph in args.output.glob("*.onnx"):
        onnx.checker.check_model(graph)
    print(json.dumps({p.name: {"bytes": p.stat().st_size, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
                      for p in sorted(args.output.iterdir()) if p.is_file()}, indent=2))


if __name__ == "__main__":
    main()
